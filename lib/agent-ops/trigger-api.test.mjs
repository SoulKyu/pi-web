test("triggerResponse: no-store JSON without the ok flag, secret only where the result carries it, errors with their status", async () => {
  const created = create({ webhook: true });
  const response = api.triggerResponse(created, 201);
  assert.equal(response.status, 201);
  assert.equal(response.headers.get("cache-control"), "no-store");
  const body = await response.json();
  assert.deepEqual(Object.keys(body).sort(), ["trigger", "webhookSecret"]);
  const patched = await api.triggerResponse(api.patchTrigger(created.trigger.id, { enabled: false })).json();
  assert.deepEqual(Object.keys(patched), ["trigger"]);
  const missing = api.triggerResponse(api.rotateSecret("nope"));
  assert.equal(missing.status, 404);
  assert.deepEqual(await missing.json(), { error: "Trigger not found" });
});

test("feed source: https URL and everyMinutes required, never a webhook", () => {
  const source = { kind: "feed", url: "https://example.com/feed.xml" };
  const ok = create({ source, everyMinutes: 30 });
  assert.equal(ok.ok, true);
  assert.deepEqual(store.getTrigger(ok.trigger.id).source, source);
  for (const bad of [{ kind: "feed", url: "http://example.com/f" }, { kind: "feed", url: "https://u:p@example.com/f" }, { kind: "feed", url: `https://e.com/${"a".repeat(2100)}` }, { kind: "feed", url: "nope" }, { kind: "rss", url: "https://e.com" }, null]) {
    const result = create({ source: bad, everyMinutes: 30 });
    assert.equal(result.ok, false, JSON.stringify(bad));
    assert.equal(result.status, 400);
  }
  assert.match(create({ source }).error, /everyMinutes/);
  assert.match(create({ source, everyMinutes: 30, webhook: true }).error, /webhook/);
  assert.match(api.rotateSecret(ok.trigger.id).error, /webhook/);
  assert.equal(api.patchTrigger(ok.trigger.id, { source: { kind: "feed", url: "http://e.com" } }).status, 400);
  assert.equal(api.patchTrigger(ok.trigger.id, { everyMinutes: null }).status, 400);
});

test("patching the feed URL clears the poll state; deleting the trigger removes it", () => {
  const made = create({ source: { kind: "feed", url: "https://example.com/a.xml" }, everyMinutes: 30 });
  const file = join(store.triggersDir(), `${made.trigger.id}.feed.json`);
  writeFileSync(file, '{"seen":["a"]}');
  api.patchTrigger(made.trigger.id, { name: "renamed" });
  assert.equal(existsSync(file), true);
  api.patchTrigger(made.trigger.id, { source: { kind: "feed", url: "https://example.com/b.xml" } });
  assert.equal(existsSync(file), false);
  writeFileSync(file, '{"seen":["a"]}');
  api.deleteTriggerById(made.trigger.id);
  assert.equal(existsSync(file), false);
});
