test("create refuses null limits and a null schedule instead of defaulting them", () => {
  for (const field of ["dedupWindowMs", "maxActiveTasks", "everyMinutes"]) {
    const result = create({ [field]: null });
    assert.equal(result.ok, false);
    assert.match(result.error, new RegExp(`${field} must be a number`));
  }
});

test("patch refuses non-boolean enabled, invalid numbers, a secret and unknown fields; nothing is written", () => {
  const created = create({ webhook: true });
  const before = store.getTrigger(created.trigger.id);
  const refused = (body, pattern) => {
    const result = api.patchTrigger(before.id, body);
    assert.equal(result.ok, false);
    assert.equal(result.status, 400);
    assert.match(result.error, pattern);
  };
  refused({ enabled: "false" }, /enabled must be a boolean/);
  refused({ enabled: null }, /enabled must be a boolean/);
  refused({ maxActiveTasks: 0 }, /maxActiveTasks/);
  refused({ dedupWindowMs: -1 }, /dedupWindowMs/);
  refused({ everyMinutes: 0 }, /everyMinutes/);
  refused({ dedupWindowMs: null }, /dedupWindowMs must be a number/);
  refused({ maxActiveTasks: null }, /maxActiveTasks must be a number/);
  refused({ dedupWindowMs: "5" }, /dedupWindowMs/);
  refused({ name: "" }, /name is required/);
  refused({ webhookSecret: "mine" }, /webhookSecret/);
  refused({ id: "00000000-0000-4000-8000-0000000000ab" }, /unknown field: id/);
  refused({ pinnedProfile: {} }, /unknown field: pinnedProfile/);
  refused([], /Invalid/);
  assert.deepEqual(store.getTrigger(before.id), before);
});

test("patch can still toggle a trigger whose profile vanished, without re-pinning", () => {
  globalProfile("vanishing");
  const created = create({ profile: "vanishing" });
  assert.equal(created.ok, true);
  const pin = store.getTrigger(created.trigger.id).pinnedProfile;
  edit("vanishing");
  const patched = api.patchTrigger(created.trigger.id, { enabled: false });
  assert.equal(patched.ok, true);
  assert.deepEqual(store.getTrigger(created.trigger.id).pinnedProfile, pin);
});

test("patch re-pins when the profile changes and refuses a profile that is not a long-term agent", () => {
  const filePath = globalProfile("reader");
  const created = create();
  const planPin = store.getTrigger(created.trigger.id).pinnedProfile;
  const patched = api.patchTrigger(created.trigger.id, { profile: "reader" });
  assert.equal(patched.ok, true);
  const after = store.getTrigger(created.trigger.id);
  assert.equal(after.profile, "reader");
  assert.notDeepEqual(after.pinnedProfile, planPin);
  assert.equal(after.pinnedProfile.filePath, filePath);
  const refused = api.patchTrigger(created.trigger.id, { profile: "explore" });
  assert.equal(refused.ok, false);
  assert.match(refused.error, /profile not found/);
  assert.equal(store.getTrigger(created.trigger.id).profile, "reader");
});

test("pinStatus: ok, drift after the profile file changes, missing once it is gone; every public view carries it", () => {
  const filePath = globalProfile("watched");
  const created = create({ profile: "watched" });
  const status = () => api.listPublicTriggers().find((t) => t.id === created.trigger.id).pinStatus;
  assert.equal(created.trigger.pinStatus, "ok");
  assert.equal(status(), "ok");
  edit("watched");
  assert.equal(status(), "drift");
  unlinkSync(filePath);
  assert.equal(status(), "missing");
});

test("repin stores the new sha and clears the drift; other fields are untouched", () => {
  const filePath = globalProfile("repinned");
  const created = create({ profile: "repinned", webhook: true });
  const before = store.getTrigger(created.trigger.id);
  edit("repinned");
  assert.equal(api.listPublicTriggers().find((t) => t.id === before.id).pinStatus, "drift");
  const result = api.patchTrigger(before.id, { repin: true });
  assert.equal(result.ok, true);
  assert.equal(result.trigger.pinStatus, "ok");
  const after = store.getTrigger(before.id);
  assert.notEqual(after.pinnedProfile.contentSha256, before.pinnedProfile.contentSha256);
  assert.equal(after.pinnedProfile.contentSha256, store.profilePinSha256({ filePath }));
  assert.deepEqual({ ...after, pinnedProfile: before.pinnedProfile }, before);
});

test("repin is refused when the profile is gone or repin is not a boolean; the pin stays", () => {
  const filePath = globalProfile("hardened");
  const created = create({ profile: "hardened" });
  const before = store.getTrigger(created.trigger.id);
  assert.equal(api.patchTrigger(before.id, { repin: "yes" }).ok, false);
  unlinkSync(filePath);
  const gone = api.patchTrigger(before.id, { repin: true });
  assert.equal(gone.ok, false);
  assert.match(gone.error, /profile not found/);
  assert.deepEqual(store.getTrigger(before.id), before);
});

test("repinTriggersOfAgent renews the pins of that agent's triggers only; a vanished profile keeps its pin", () => {
  globalProfile("pinned");
  globalProfile("bystander");
  const mine = [create({ profile: "pinned" }), create({ profile: "pinned", name: "second" })].map((r) => r.trigger.id);
  const other = create({ profile: "bystander" }).trigger.id;
  const before = Object.fromEntries([...mine, other].map((id) => [id, store.getTrigger(id).pinnedProfile.contentSha256]));
  edit("pinned");
  edit("bystander");
  assert.equal(api.listPublicTriggers().find((t) => t.id === mine[0]).pinStatus, "drift");
  assert.equal(api.repinTriggersOfAgent("pinned"), 2);
  for (const id of mine) {
    assert.notEqual(store.getTrigger(id).pinnedProfile.contentSha256, before[id]);
    assert.equal(api.listPublicTriggers().find((t) => t.id === id).pinStatus, "ok");
  }
  assert.equal(store.getTrigger(other).pinnedProfile.contentSha256, before[other]);
  unlinkSync(reg.resolveLongTermProfile("pinned").filePath);
  const kept = store.getTrigger(mine[0]).pinnedProfile;
  assert.equal(api.repinTriggersOfAgent("pinned"), 0);
  assert.deepEqual(store.getTrigger(mine[0]).pinnedProfile, kept);
});

test("deleteTriggersOfAgent removes only that agent's triggers", () => {
  globalProfile("doomed");
  globalProfile("survivor");
  const doomed = [create({ profile: "doomed" }), create({ profile: "doomed" })].map((r) => r.trigger.id);
  const survivor = create({ profile: "survivor" }).trigger.id;
  assert.equal(api.deleteTriggersOfAgent("doomed"), 2);
  for (const id of doomed) assert.equal(store.getTrigger(id), null);
  assert.ok(store.getTrigger(survivor));
  assert.equal(api.deleteTriggersOfAgent("doomed"), 0);
});

